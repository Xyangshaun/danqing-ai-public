// 检查ID重复
const existingIds = new Set(existing.map(a => a.id));
const duplicates = newArtworks.filter(a => existingIds.has(a.id));
if (duplicates.length > 0) {
  console.error('❌ 以下ID重复:', duplicates.map(d => d.id));
  process.exit(1);
}

// 验证必填字段
const requiredFields = ['id', 'title', 'artist', 'year', 'category', 'style', 'era', 'region', 'description', 'imageUrl', 'source', 'tags'];
const invalid = newArtworks.filter(a => {
  const missing = requiredFields.filter(f => !a[f]);
  if (missing.length) {
    console.error(`❌ ${a.id} 缺少字段: ${missing.join(', ')}`);
    return true;
  }
  return false;
});
if (invalid.length > 0) process.exit(1);

// 合并
const merged = [...existing, ...newArtworks];
writeFileSync(ARTWORKS_PATH, JSON.stringify(merged, null, 2) + '\n', 'utf8');

